/* Service Worker für „Uniforme Polyeder“
   Alle Dateien werden beim ersten Start zwischengespeichert. Danach startet die App
   immer aus dem Cache (auch ohne Internet) und lädt im Hintergrund neue Versionen nach,
   die beim nächsten Start angezeigt werden. */
const CACHE = 'polyeder-v1';
const ASSETS = [
  './',
  './index.html',
  './manifest.webmanifest',
  './apple-touch-icon.png',
  './icon-192.png',
  './icon-512.png',
  './icon-maskable-512.png'
];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    let cached = await cache.match(req, { ignoreSearch: true });
    if (!cached && req.mode === 'navigate') cached = await cache.match('./index.html');
    const network = fetch(req)
      .then(res => { if (res && res.ok && !res.redirected) cache.put(req, res.clone()); return res; })
      .catch(() => undefined);
    if (cached){ event.waitUntil(network); return cached; }
    const res = await network;
    return res || new Response('Offline', { status: 503, statusText: 'Offline' });
  })());
});
